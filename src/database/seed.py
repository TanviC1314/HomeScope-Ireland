"""Generate ``database/seed_data.sql`` (reference dimensions) from ``src/data_cleaning/reference.py``.

Keeping the SQL seed generated from the Python reference guarantees both stay identical
(a unit test checks this).  Run:  python -m src.database.seed
"""
from __future__ import annotations

from src.data_cleaning import reference as ref
from src.utils.paths import DATABASE_DIR


def _q(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def build_seed_sql() -> str:
    regions = ",\n    ".join(f"({_q(r.region_name)}, {_q(r.region_type)})" for r in ref.region_frame().itertuples())
    counties = ",\n    ".join(f"({_q(c)}, {_q(p)}, {_q(n)}, {_q(h)})" for c, p, n, h in ref.COUNTIES)
    las = ",\n    ".join(f"({_q(n)}, {_q(c)}, {_q(t)})" for n, c, t in ref.LOCAL_AUTHORITIES)
    return f"""-- HomeScope Ireland - reference data seed (GENERATED by `python -m src.database.seed`; do not edit by hand)
-- Source of truth: src/data_cleaning/reference.py

INSERT INTO dim_region (region_name, region_type) VALUES
    {regions}
ON CONFLICT (region_type, region_name) DO NOTHING;

INSERT INTO dim_county (county_name, province, nuts3_region_id, homeless_region_id)
SELECT v.county_name, v.province, rn.region_id, rh.region_id
FROM (VALUES
    {counties}
) AS v (county_name, province, nuts3_region, homeless_region)
JOIN dim_region rn ON rn.region_type = 'NUTS3'    AND rn.region_name = v.nuts3_region
JOIN dim_region rh ON rh.region_type = 'HOMELESS' AND rh.region_name = v.homeless_region
ON CONFLICT (county_name) DO NOTHING;

INSERT INTO dim_local_authority (la_name, county_id, la_type)
SELECT v.la_name, c.county_id, v.la_type
FROM (VALUES
    {las}
) AS v (la_name, county_name, la_type)
JOIN dim_county c ON c.county_name = v.county_name
ON CONFLICT (la_name) DO NOTHING;
"""


def write_seed() -> None:
    (DATABASE_DIR / "seed_data.sql").write_text(build_seed_sql(), encoding="utf-8")


if __name__ == "__main__":
    write_seed()
    print("wrote database/seed_data.sql")
