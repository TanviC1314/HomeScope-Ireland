"""Execute every query in ``database/queries.sql`` and show / export the results.

    python -m src.database.run_queries                 # run all, print a short preview of each
    python -m src.database.run_queries --markdown      # also write docs/SQL_RESULTS.md (snapshot of top rows)
"""
from __future__ import annotations

import argparse
import re
from dataclasses import dataclass
from typing import Dict, List, Optional

import pandas as pd
from sqlalchemy.engine import Engine

from src.database.connection import get_engine
from src.utils.logging_config import get_logger
from src.utils.paths import DATABASE_DIR, DOCS_DIR

log = get_logger("sql")


@dataclass
class Query:
    name: str
    question: str
    techniques: str
    caveat: str
    sql: str


def parse_queries(text: str) -> List[Query]:
    """Split queries.sql into documented queries (blocks start with '-- name:')."""
    blocks = re.split(r"^-- name:\s*", text, flags=re.MULTILINE)[1:]
    queries: List[Query] = []
    for block in blocks:
        lines = block.splitlines()
        name = lines[0].strip()
        meta = {"question": "", "techniques": "", "caveat": ""}
        body: List[str] = []
        for line in lines[1:]:
            m = re.match(r"^--\s*(question|techniques|caveat|note):\s*(.*)$", line)
            if m:
                key = "caveat" if m.group(1) in ("caveat", "note") else m.group(1)
                meta[key] = (meta[key] + " " + m.group(2)).strip()
            elif line.startswith("--") and not body:
                continue
            else:
                body.append(line)
        sql = "\n".join(body).strip().rstrip(";") + ";"
        queries.append(Query(name, meta["question"], meta["techniques"], meta["caveat"], sql))
    return queries


def load_queries() -> List[Query]:
    return parse_queries((DATABASE_DIR / "queries.sql").read_text(encoding="utf-8"))


def run_query(engine: Engine, query: Query) -> pd.DataFrame:
    # psycopg2 treats '%' as a parameter marker; escape literal percent signs (e.g. '40%+ rise').
    # The .sql file itself stays valid for plain psql.
    with engine.connect() as conn:
        result = conn.exec_driver_sql(query.sql.replace("%", "%%"))
        return pd.DataFrame(result.fetchall(), columns=list(result.keys()))


def run_all(engine: Optional[Engine] = None) -> Dict[str, pd.DataFrame]:
    engine = engine or get_engine()
    return {q.name: run_query(engine, q) for q in load_queries()}


def to_markdown(queries: List[Query], results: Dict[str, pd.DataFrame], rows: int = 5) -> str:
    out = ["# SQL analysis results (snapshot)", "",
           "Generated by `python -m src.database.run_queries --markdown` against the loaded PostgreSQL database. "
           f"Each section shows the question, SQL techniques used and the first {rows} rows. "
           "Full SQL is in [`database/queries.sql`](../database/queries.sql).", ""]
    for q in queries:
        df = results[q.name]
        out += [f"## {q.name}", f"**Question:** {q.question}", "", f"**Techniques:** {q.techniques}", ""]
        if q.caveat:
            out += [f"**Caveat:** {q.caveat}", ""]
        out += [f"_{len(df)} rows returned_", "", df.head(rows).to_markdown(index=False) if not df.empty else "_no rows_", ""]
    return "\n".join(out)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--markdown", action="store_true", help="write docs/SQL_RESULTS.md")
    ap.add_argument("--rows", type=int, default=3)
    args = ap.parse_args()
    engine = get_engine()
    queries = load_queries()
    results: Dict[str, pd.DataFrame] = {}
    failures = 0
    for q in queries:
        try:
            df = run_query(engine, q)
            results[q.name] = df
            log.info("%-58s %5d rows", q.name, len(df))
            if args.rows and not args.markdown:
                print(df.head(args.rows).to_string(index=False), "\n")
        except Exception as exc:
            failures += 1
            log.error("%s FAILED: %s", q.name, str(exc).splitlines()[0])
    if args.markdown and not failures:
        DOCS_DIR.mkdir(exist_ok=True)
        (DOCS_DIR / "SQL_RESULTS.md").write_text(to_markdown(queries, results), encoding="utf-8")
        log.info("wrote docs/SQL_RESULTS.md")
    raise SystemExit(1 if failures else 0)


if __name__ == "__main__":
    main()
